// Copies the compiled MandateSettler ABI into the app so the UI/agents and the contract never drift.
import fs from "node:fs";
const art = JSON.parse(fs.readFileSync(new URL("../../chain/artifacts/contracts/MandateSettler.sol/MandateSettler.json", import.meta.url)));
fs.mkdirSync(new URL("../src/lib/generated/", import.meta.url), { recursive: true });
fs.writeFileSync(
  new URL("../src/lib/generated/settler.ts", import.meta.url),
  `// AUTO-GENERATED by scripts/sync-abi.mjs - do not edit\nexport const settlerAbi = ${JSON.stringify(art.abi, null, 2)} as const;\n`,
);
console.log("settler ABI synced");
